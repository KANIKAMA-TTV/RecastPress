"""Supervise one same-job fixed C context module, without executing PHP.

Unsupported contexts, syscall failures, stack overlap, normal context-entry
return and failed guest execution remain failures. This is not Fiber support.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import platform
import subprocess
import sys

import check as host
from language_check import equal, parse_json

HERE, ROOT = host.HERE, host.ROOT
BUILD = ROOT / 'experiments/php-wasix-context-probe'
MANIFEST = BUILD / 'manifest.json'
RECEIPT = BUILD / 'evidence/build.json'
SOURCE = BUILD / 'fixtures/context_contract.c'
MODULE = ROOT / 'target/php-wasix-context-probe/context.wasm'
_context_spec = importlib.util.spec_from_file_location('recastpress_context_build', BUILD / 'build.py')
context_build = importlib.util.module_from_spec(_context_spec)
_context_spec.loader.exec_module(context_build)
sys.path.insert(0, str(ROOT / 'scripts'))
import owned_probe

require, digest = host.require, host.digest
CHECKS = [
    'main_self_switch', 'a_self_switch', 'destroy_main_rejected', 'destroy_self_a_rejected',
    'destroy_main_from_a_rejected', 'ranges_disjoint', 'canaries_preserved', 'trace_matches',
    'destroy_a_succeeded', 'switch_destroyed_a_rejected', 'destroy_a_twice_succeeded',
    'b_continued_after_a_destroy', 'b_recursion_unwound', 'destroy_b_succeeded',
    'switch_destroyed_b_rejected', 'destroy_b_twice_succeeded',
    'a_recursion_unwound', 'main_clobber_after_a_unwind', 'b_preserved_after_a_unwind',
]
ERRORS = ['destroy_main_from_main', 'destroy_self_a', 'destroy_main_from_a',
          'switch_destroyed_a', 'switch_destroyed_b']
KEYS = {'schema', 'ok', 'phase', 'failure', 'failure_return', 'failure_errno', 'abi', 'contexts',
        'rounds', 'depth', 'a_rounds', 'b_rounds', 'a_ready', 'b_ready', 'b_done',
        'a_resumed_after_destroy', 'a_done', 'a_unwound_frames', 'b_unwound_frames',
        'range_observation', 'range_count', 'ranges', 'trace', 'checks', 'errors'}


def read_fixed(path, limit):
    require(path.resolve(strict=True) == ROOT.resolve() / path.relative_to(ROOT), 'fixed input resolves through symlink')
    require(path.is_file() and 0 < path.stat().st_size <= limit, 'fixed input type/size')
    before = path.stat().st_size
    with path.open('rb') as source:
        wire = source.read(limit + 1)
    require(len(wire) == before and len(wire) <= limit, 'fixed input changed while reading')
    return wire


def source_hashes():
    paths = host.compiled_inputs() + [Path(__file__).resolve(), HERE / 'check.py', HERE / 'language_check.py',
                                    ROOT / 'scripts/owned_probe.py', MANIFEST, SOURCE, BUILD / 'build.py']
    hashes = {path.relative_to(ROOT).as_posix(): digest(path) for path in paths}
    driver_hashes = context_build.input_hashes()
    require(type(driver_hashes) is dict and driver_hashes, 'context build input hashes missing')
    for name, value in driver_hashes.items():
        if name in hashes:
            equal(hashes[name], value, 'shared context input identity')
        hashes[name] = value
    return hashes


def verify_build():
    # The build owner verifies pinned tools/assets/commands and current sources.
    # Store only a digest of that stable provenance, never arbitrary tool paths.
    verified = context_build.verify_build()
    require(type(verified) is dict and verified, 'context build verifier returned no provenance')
    wire = read_fixed(RECEIPT, 2 * 1024 * 1024)
    receipt = parse_json(wire)
    for key, expected in [('format_version', 1), ('outcome', 'context_candidate_built_not_executed'),
                          ('phase', 'build_complete'), ('guest_executed', False)]:
        equal(receipt[key], expected, 'context build ' + key)
    manifest = read_fixed(MANIFEST, 256 * 1024)
    source = read_fixed(SOURCE, 256 * 1024)
    for path, data in [(MANIFEST, manifest), (SOURCE, source)]:
        equal(receipt['input_files'][path.relative_to(ROOT).as_posix()], hashlib.sha256(data).hexdigest(),
              'context build input binding')
    module = read_fixed(MODULE, 16 * 1024 * 1024)
    equal(receipt['context_wasm']['path'], MODULE.relative_to(ROOT).as_posix(), 'fixed generated module')
    equal(receipt['context_wasm']['bytes'], len(module), 'generated byte count')
    equal(receipt['context_wasm']['sha256'], hashlib.sha256(module).hexdigest(), 'generated module digest')
    equal(receipt['context_wasm']['wasm_header_verified'], True, 'generated Wasm observation')
    equal(receipt['context_wasm']['executed'], False, 'build does not run the guest')
    require(module.startswith(b'\0asm\x01\0\0\0'), 'generated module is not Wasm v1')
    return {'build_receipt_sha256': hashlib.sha256(wire).hexdigest(),
            'manifest_sha256': hashlib.sha256(manifest).hexdigest(),
            'source_sha256': hashlib.sha256(source).hexdigest(),
            'module_bytes': len(module), 'module_sha256': hashlib.sha256(module).hexdigest(),
            'build_verifier_provenance_sha256': hashlib.sha256(
                json.dumps(verified, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode()).hexdigest(),
            'scope': 'same-job trusted source/tool observations; no signed-attestation or reproducible-build claim'}


def validate_guest(value):
    require(type(value) is dict and set(value) == KEYS, 'context result field inventory')
    for key, expected in [('schema', 'recastpress.wasix-context-c.v0.5'), ('ok', True), ('phase', 'complete'),
                          ('failure', None), ('failure_return', 0), ('failure_errno', 0), ('rounds', 8), ('depth', 4),
                          ('a_rounds', 8), ('b_rounds', 10), ('a_ready', True), ('b_ready', True), ('b_done', True),
                          ('a_done', True), ('a_unwound_frames', 4), ('b_unwound_frames', 4),
                          ('range_observation', 'initial-simultaneous-live-snapshot'),
                          ('a_resumed_after_destroy', 0), ('range_count', 9)]:
        equal(value[key], expected, 'context C ' + key)
    equal(value['abi'], {'context_id_bytes': 8, 'pointer_bytes': 4, 'einval': 28}, 'context C ABI')
    equal(value['checks'], dict.fromkeys(CHECKS, True), 'context C checks')
    equal(value['errors'], {name: {'return': -1, 'errno': 28} for name in ERRORS}, 'rejected operations')
    contexts = value['contexts']
    require(type(contexts) is dict and set(contexts) == {'main', 'a', 'b'}, 'context IDs')
    equal(contexts['main'], 0, 'main context ID')
    require(all(type(contexts[k]) is int and 0 < contexts[k] <= 2**64 - 1 for k in ['a', 'b'])
            and contexts['a'] != contexts['b'], 'context IDs must be distinct nonzero uint64')
    equal(value['trace'], [10, 20] + [event for round_ in range(8) for event in [100 + round_, 200 + round_]]
          + [40, 208, 209, 30], 'context execution trace')
    ranges = value['ranges']
    require(type(ranges) is list and len(ranges) == 9, 'context stack range count')
    seen = set()
    for row in ranges:
        require(type(row) is dict and set(row) == {'owner', 'depth', 'begin', 'end'}, 'range fields')
        require(type(row['owner']) is str and type(row['depth']) is int, 'range owner/depth types')
        identity = row['owner'], row['depth']
        require(identity not in seen, 'duplicate context stack owner/depth')
        seen.add(identity)
        require(type(row['begin']) is int and type(row['end']) is int
                and 0 <= row['begin'] < row['end'] <= 2**32 - 1, 'context stack interval')
    equal(seen, {('main', 0)} | {(owner, depth) for owner in ['a', 'b'] for depth in range(4)}, 'range coverage')
    for index, left in enumerate(ranges):
        for right in ranges[index + 1:]:
            require(left['end'] <= right['begin'] or right['end'] <= left['begin'], 'context linear-stack overlap')


def validate_result(value, pid, backend, provenance):
    for key, expected in [('schema', 'recastpress.wasix-context-host.v0.5'), ('process_pid', pid),
                          ('engine', 'wasmer-7.2.0/' + backend), ('phase', 'context_contract_verified'),
                          ('ok', True), ('engine_supports_async', True), ('context_contract_verified', True),
                          ('guest_completed', True), ('guest_json_decoded', True), ('module_compile_invocations', 1),
                          ('runtime_shutdown_returned', True), ('runtime_shutdown_wait_limit_ms', 2000),
                          ('stdout_eof', True), ('stderr_eof', True), ('stdout_overflow', False), ('stderr_overflow', False),
                          ('stderr_bytes', 0), ('stderr_hex', ''), ('php_executed', False),
                          ('php_fiber_compatibility_verified', False), ('real_db', False), ('wordpress_executed', False),
                          ('full_php_compatibility_verified', False), ('memory_limit_verified', False),
                          ('cpu_limit_verified', False), ('all_resources_immediately_reclaimed', False),
                          ('sysroot_source_build_attestation_verified', False),
                          ('product_adopted', False)]:
        equal(value[key], expected, 'host ' + key)
    require('host_execution_error' not in value, 'host retained a guest execution failure')
    for key, expected in [('path', MODULE.relative_to(ROOT).as_posix()), ('verified', True),
                          ('observed_bytes', provenance['module_bytes']), ('observed_sha256', provenance['module_sha256'])]:
        equal(value['artifact'][key], expected, 'host artifact ' + key)
    for key, expected in [('path', SOURCE.relative_to(ROOT).as_posix()), ('verified', True),
                          ('observed_sha256', provenance['source_sha256'])]:
        equal(value['source'][key], expected, 'host C source ' + key)
    for key, expected in [('verified', True), ('full_source_tool_chain_verified_by_host', False),
                          ('observed_sha256', provenance['build_receipt_sha256']),
                          ('manifest_sha256', provenance['manifest_sha256'])]:
        equal(value['build_receipt'][key], expected, 'host build receipt ' + key)
    equal(value['guest_arguments'], [], 'no arbitrary guest arguments')
    isolation = value['isolation']
    for key in ['host_environment_forwarded', 'home_mapped', 'host_directories_mapped', 'http_client', 'deep_sleep',
                'memory_limit_enforced', 'in_process_deadline_enforced', 'other_virtual_root_writes_forbidden']:
        equal(isolation[key], False, 'isolation ' + key)
    equal(isolation['asynchronous_threading'], True, 'async WASIX context execution')
    equal(isolation['configured_guest_max_threads'], 1, 'thread capability')
    equal(isolation['networking'], 'UnsupportedVirtualNetworking', 'network implementation')
    equal(isolation['guest_environment_supplied'], [], 'no guest environment supplied')
    equal(isolation['guest_mounts'], [], 'no guest mounts supplied')
    equal(isolation['stdin'], 'closed-pipe', 'closed guest input')
    for key in ['stdout_limit_bytes', 'stderr_limit_bytes']:
        equal(isolation[key], 65536, 'capture ' + key)
    for key in ['compile_elapsed_ms', 'guest_execution_elapsed_ms']:
        require(type(value[key]) is int and value[key] >= 0, 'invalid elapsed span')
    wire = bytes.fromhex(value['stdout_hex'])
    require(0 < len(wire) <= 65536 and wire.endswith(b'\n') and wire.count(b'\n') == 1,
            'one bounded terminated guest JSON required')
    equal(len(wire), value['stdout_bytes'], 'guest capture byte count')
    equal(hashlib.sha256(wire).hexdigest(), value['stdout_sha256'], 'guest capture digest')
    guest = parse_json(wire)
    equal(guest, value['guest_json'], 'raw/decoded guest result consistency')
    validate_guest(guest)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--llvm', action='store_true')
    parser.add_argument('--record', action='store_true')
    args = parser.parse_args()
    backend = 'llvm' if args.llvm else 'cranelift'
    report = {'format_version': 1, 'observed_at_utc': datetime.now(timezone.utc).isoformat(),
              'platform': {'system': platform.system(), 'machine': platform.machine()}, 'backend': backend,
              'scope': 'one fixed C WASIX context program only', 'outcome': 'not_run',
              'context_contract_passed': False, 'owned_host_reaped': False,
              'php_executed': False, 'php_fiber_compatibility_verified': False,
              'product_runtime_selected': False, 'memory_limit_verified': False,
              'cpu_limit_verified': False, 'all_resources_immediately_reclaimed': False,
              'sysroot_source_build_attestation_verified': False,
              'outer_build_timeout_seconds': 1200, 'outer_execution_timeout_seconds': 60}
    passed, stage = False, 'build_provenance'
    try:
        require(platform.system() == 'Linux', 'context contract requires its Linux build job')
        before = source_hashes()
        report['input_files'] = before
        provenance = verify_build()
        report['generated_provenance'] = provenance
        stage = 'host_build'
        environment = os.environ.copy()
        command = ['cargo', 'build', '--release', '--manifest-path', str(HERE / 'Cargo.toml'),
                   '--target-dir', str(host.TARGET), '--locked', '--offline', '--message-format=json']
        if args.llvm:
            command += ['--no-default-features', '--features', 'llvm']
        _, built = owned_probe.run_captured_probe(command, environment, timeout=1200)
        report['build_exit_code'] = built.returncode
        if built.returncode:
            report['diagnostics'] = host.diagnostic(built.stderr, 8192)
        require(built.returncode == 0, 'context host build failed')
        executable = host.select_artifact(built.stdout)
        binary_sha = digest(executable)
        report['native_artifact'] = executable.relative_to(ROOT).as_posix()
        report['native_artifact_sha256'] = binary_sha
        stage = 'execution'
        child_environment = {key: val for key, val in environment.items() if key.upper() not in {
            'GH_TOKEN', 'GITHUB_TOKEN', 'ACTIONS_RUNTIME_TOKEN', 'RUST_LOG', 'RUST_BACKTRACE'}}
        pid, result = owned_probe.run_captured_probe([str(executable), '--context-contract'], child_environment, timeout=60)
        report.update(owned_process_pid=pid, owned_host_reaped=True, exit_code=result.returncode)
        require(len(result.stdout) <= 512 * 1024 and len(result.stderr) <= 65536, 'host capture budget')
        report['host_stderr_sha256'] = hashlib.sha256(result.stderr).hexdigest()
        phases = [line.split('=', 1)[1] for line in result.stderr.decode('utf-8', errors='replace').splitlines()
                  if line.startswith('WASIX_CONTEXT_PHASE=')]
        report['observed_phases'] = phases
        if result.stderr:
            report['host_stderr_excerpt'] = host.diagnostic(result.stderr, 8192)
        require(result.stdout.endswith(b'\n') and result.stdout.count(b'\n') == 1, 'one terminated host JSON required')
        value = parse_json(result.stdout)
        # Failed guest JSON and its captures stay in the receipt before verdict.
        report['native_result'] = value
        equal(source_hashes(), before, 'context source hashes after execution')
        equal(digest(executable), binary_sha, 'context native executable unchanged')
        equal(verify_build(), provenance, 'context provenance after execution')
        require(result.returncode == 0, 'fixed context host execution failed')
        stage = 'contract_verification'
        equal(phases, ['module_compile', 'context_execution'], 'context execution phases')
        validate_result(value, pid, backend, provenance)
        report['context_contract_passed'], passed = True, True
        report['outcome'] = 'fixed_c_context_contract_passed'
    except subprocess.TimeoutExpired as error:
        report['outcome'] = stage + '_timeout'
        report['diagnostics'] = 'owned child exceeded finite deadline'
        if error.stderr:
            report['host_stderr_excerpt'] = host.diagnostic(error.stderr, 8192)
    except (Exception, KeyboardInterrupt) as error:
        report['outcome'] = stage + '_failed'
        report['diagnostics'] = str(error)[:8192]
    finally:
        try:
            owned_probe.reap_owned_probes()
        except (Exception, KeyboardInterrupt) as error:
            report['outcome'], report['context_contract_passed'], passed = 'cleanup_failed', False, False
            report['cleanup_diagnostics'] = str(error)[:8192]
    if args.record:
        directory = HERE / 'evidence'
        directory.mkdir(exist_ok=True)
        (directory / (platform.system().lower() + '-' + backend + '-context-contract.json')).write_text(
            json.dumps(report, indent=2, ensure_ascii=True) + '\n', encoding='utf-8', newline='\n')
    print('WASIX fixed C context: ' + report['outcome'])
    return 0 if passed else 1


if __name__ == '__main__':
    sys.exit(main())
