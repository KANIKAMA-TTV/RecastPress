"""Pinned PHP observations for an explicit XML/UTF-8 profile, not PHP table code."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

import wordpress_entity_names as html
import wordpress_reference as reference

ARTIFACT = "compatibility/wordpress-xml-utf8-entities.json"
RUST_DATA = "crates/recastpress-wp/src/xml_entity_mapping.rs"
PHP_VERSION = "8.5.12"
PHP_SHA256 = "02273af2cb60375c95d1a4d9244fd1bb8abad898e63055235a06ee36af0380ef"
PHP_ARCHIVE_SHA256 = "2ab242af38d76bdf417cde5ec048b1bcd76a5a40f39a3d15d5f046f38571c477"
MAPPING_SHA256 = "6810e6d66a468cf2a7b75a0969b932fd727553dc7141090bd837d6023331c25b"
XML_NAMES = ["amp", "lt", "gt", "apos", "quot"]


def pair_hash(pairs):
    return hashlib.sha256(json.dumps(pairs, separators=(",", ":"), ensure_ascii=True).encode("ascii")).hexdigest()


def profile():
    return {"context": "xml", "charset": "UTF-8", "php_version": PHP_VERSION,
            "html5_flag": 48, "html_names_count": 253, "xml_names_count": 5,
            "source_sha256": html.SOURCE_SHA256, "ordered_names_sha256": html.ORDERED_NAMES_SHA256,
            "mapping_sha256": MAPPING_SHA256, "php_binary_sha256": PHP_SHA256}


def extract_xml_names(source):
    matches = list(re.finditer(r"\$allowedxmlentitynames\s*=\s*array\(", source))
    if len(matches) != 1:
        raise ValueError("XML literal assignment missing or ambiguous")
    start = matches[0].end()
    end = source.find(");", start)
    body = source[start:end] if end >= 0 else ""
    if not re.fullmatch(r"(?:\s*'[A-Za-z]+'\s*,)+\s*", body):
        raise ValueError("XML literal contains nonliteral data")
    names = re.findall(r"'([A-Za-z]+)'", body)
    if names != XML_NAMES:
        raise ValueError("XML name order differs")
    return names


def validate_pairs(pairs):
    names = html.read_names()
    if (not isinstance(pairs, list) or len(pairs) != 253
            or any(not isinstance(pair, list) or len(pair) != 2 or type(pair[0]) is not str
                   or type(pair[1]) is not str or not re.fullmatch(r"(?:[0-9a-f]{2})+", pair[1]) for pair in pairs)
            or [pair[0] for pair in pairs] != names or pair_hash(pairs) != MAPPING_SHA256):
        raise ValueError("XML observed mapping identity differs")
    for name, wire in pairs:
        decoded = bytes.fromhex(wire).decode("utf-8")
        if name in XML_NAMES and decoded != "&" + name + ";":
            raise ValueError("XML predefined name was not preserved")
    return pairs


def generated(pairs):
    validate_pairs(pairs)
    record = {"format_version": 1, "wordpress_version": reference.VERSION,
              "source_path": html.SOURCE_PATH, **profile(), "xml_names": XML_NAMES,
              "php_archive_sha256": PHP_ARCHIVE_SHA256,
              "observation_sources": {path: reference.digest_file(reference.ROOT / path)
                                      for path in ("scripts/wordpress_xml_entity_mapping.php", "scripts/reference_functions.php")},
              "pairs": pairs}
    artifact = json.dumps(record, indent=2, ensure_ascii=True) + "\n"
    rust = ("// Generated by scripts/wordpress_xml_entity_mapping.py: pinned PHP observations.\n"
            "// XML5 remain references; other fixed HTML names map to UTF-8. Not a general HTML5 decoder.\n"
            "pub(super) const SORTED_XML: [(&[u8], &[u8]); 253] = [\n"
            + "".join('    (b"' + name + '", b"' + ''.join('\\x' + wire[i:i+2] for i in range(0, len(wire), 2)) + '"),\n'
                      for name, wire in sorted(pairs)) + "];\n")
    return artifact, rust


def read_pairs():
    path = reference.ROOT / ARTIFACT
    with path.open("rb") as stream:
        wire = stream.read(65537)
    if len(wire) > 65536:
        raise ValueError("XML mapping artifact exceeds host read bound")
    # Exact generated bytes below also reject duplicate/unknown fields.
    record = json.loads(wire)
    pairs = validate_pairs(record["pairs"])
    if wire != generated(pairs)[0].encode():
        raise ValueError("XML mapping artifact is stale")
    return pairs


def check():
    html.check()
    source = reference.REFERENCE / f"wordpress-{reference.VERSION}" / html.SOURCE_PATH
    extract_xml_names(source.read_text(encoding="utf-8"))
    pairs = read_pairs()
    for relative, expected in zip((ARTIFACT, RUST_DATA), generated(pairs)):
        with (reference.ROOT / relative).open("rb") as stream:
            actual = stream.read(len(expected.encode()) + 1)
        if actual != expected.encode():
            raise ValueError("XML mapping data is stale: " + relative)


def observe(php):
    html.check()
    if reference.digest_file(php) != PHP_SHA256:
        raise ValueError("XML observation PHP executable differs")
    source = reference.REFERENCE / f"wordpress-{reference.VERSION}"
    xml = extract_xml_names((source / html.SOURCE_PATH).read_text(encoding="utf-8"))
    run = subprocess.run([str(php), "-n", str(reference.ROOT / "scripts/wordpress_xml_entity_mapping.php"), str(source)],
                         input=json.dumps({"html_names": html.read_names(), "xml_names": xml}).encode(),
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True, timeout=30)
    if run.stderr or len(run.stdout) > 65536:
        raise ValueError("XML mapping observation emitted diagnostics or exceeded bound")
    record = json.loads(run.stdout)
    expected = {"php_version": PHP_VERSION, "php_int_size": 8, "charset": "UTF-8", "html5_flag": 48}
    if set(record) != {*expected, "pairs"} or any(type(record[key]) is not type(value) or record[key] != value for key, value in expected.items()):
        raise ValueError("XML observation runtime profile differs")
    return validate_pairs(record["pairs"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--php", type=Path)
    args = parser.parse_args()
    if args.php:
        pairs = observe(args.php)
        if not args.check:
            for path, wire in zip((ARTIFACT, RUST_DATA), generated(pairs)):
                (reference.ROOT / path).write_text(wire, encoding="utf-8", newline="\n")
        else:
            if pairs != read_pairs():
                raise ValueError("XML PHP observations differ from stored mapping")
    elif not args.check:
        parser.error("generation requires --php with the pinned development executable")
    check()
    print("XML UTF-8 observations match: 253 names, XML5 preserved")


if __name__ == "__main__":
    main()
