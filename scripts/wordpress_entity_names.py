"""Extract only the pinned KSES HTML entity-name data literal; never execute PHP."""

import argparse
import hashlib
import json
import re

import wordpress_reference as reference

SOURCE_PATH = "wp-includes/kses.php"
SOURCE_SHA256 = "ead6be7192295b9e7417c2146704c1935748f92b9ef4f6adca193a0e4118469d"
ORDERED_NAMES_SHA256 = "60c1fcc052465d98ef468f0a6080aa422a457d5e77c9b7d8d72d40179c21c512"
COUNT = 253
ARTIFACT = "compatibility/wordpress-default-html-entities.json"
RUST_DATA = "crates/recastpress-wp/src/entity_names.rs"


def extract_names(source):
    assignments = list(re.finditer(r"\$allowedentitynames\s*=\s*array\(", source))
    if len(assignments) != 1:
        raise ValueError("HTML entity data assignment is missing or ambiguous")
    start = assignments[0].end()
    end = source.find(");", start)
    if end < 0:
        raise ValueError("HTML entity data literal is not terminated")
    body = source[start:end]
    if not re.fullmatch(r"(?:\s*'[A-Za-z][A-Za-z0-9]*'\s*,)+\s*", body):
        raise ValueError("HTML entity data contains something other than string literals")
    names = re.findall(r"'([A-Za-z][A-Za-z0-9]*)'", body)
    if len(set(names)) != len(names) or any(not re.fullmatch(r"[A-Za-z]{2,8}[0-9]{0,2}", name) for name in names):
        raise ValueError("HTML entity names are duplicated or outside the callback grammar")
    return names


def names_hash(names):
    return hashlib.sha256(json.dumps(names, separators=(",", ":"), ensure_ascii=True).encode("ascii")).hexdigest()


def profile():
    return {"context": "html", "names_count": COUNT, "source_sha256": SOURCE_SHA256,
            "ordered_names_sha256": ORDERED_NAMES_SHA256}


def generated():
    source = reference.REFERENCE / f"wordpress-{reference.VERSION}" / SOURCE_PATH
    with source.open("rb") as stream:
        raw = stream.read(1024 * 1024 + 1)
    if len(raw) > 1024 * 1024 or hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("KSES source identity differs from the pinned entity-data baseline")
    names = extract_names(raw.decode("utf-8"))
    if len(names) != COUNT or names_hash(names) != ORDERED_NAMES_SHA256:
        raise ValueError("HTML entity data count/order differs from the pinned baseline")
    record = {"format_version": 1, "wordpress_version": reference.VERSION,
              "source_path": SOURCE_PATH, "source_line": 639, **profile(), "names": names}
    artifact = json.dumps(record, indent=2, ensure_ascii=True) + "\n"
    rust = ("// Generated by scripts/wordpress_entity_names.py from pinned WordPress KSES data.\n"
            "// HTML default-name membership only; no Unicode mapping or XML entity table.\n"
            f"pub(super) const SORTED_NAMES: [&[u8]; {COUNT}] = [\n"
            + "".join(f'    b"{name}",\n' for name in sorted(names)) + "];\n")
    return artifact, rust


def read_names():
    with (reference.ROOT / ARTIFACT).open("rb") as stream:
        wire = stream.read(65537)
    if len(wire) > 65536:
        raise ValueError("recorded HTML entity data exceeds its host read bound")
    record = json.loads(wire.decode("utf-8"))
    names = record["names"]
    if (not isinstance(names, list) or len(names) != COUNT
            or any(type(name) is not str for name in names) or names_hash(names) != ORDERED_NAMES_SHA256):
        raise ValueError("recorded HTML entity names differ from the pinned baseline")
    return names


def check():
    for path, expected in zip((ARTIFACT, RUST_DATA), generated()):
        expected_wire = expected.encode("utf-8")
        with (reference.ROOT / path).open("rb") as stream:
            actual = stream.read(len(expected_wire) + 1)
        if actual != expected_wire:
            raise ValueError("HTML entity data is stale: " + path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    if options.check:
        check()
    else:
        for path, wire in zip((ARTIFACT, RUST_DATA), generated()):
            (reference.ROOT / path).write_text(wire, encoding="utf-8", newline="\n")
    print("Pinned HTML default entity names match: 253 data literals; no PHP execution")


if __name__ == "__main__":
    main()
